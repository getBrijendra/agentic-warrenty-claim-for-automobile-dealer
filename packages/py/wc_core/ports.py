"""Ports (P1: hexagonal). Domain code depends only on these Protocols, never on vendor SDKs."""
from __future__ import annotations

from datetime import datetime
from typing import Any, Iterator, Protocol, runtime_checkable


class NotConfigured(RuntimeError):
    """Raised by stub adapters for real systems that are not wired up yet."""


@runtime_checkable
class DmsPort(Protocol):
    def capabilities(self) -> dict: ...
    def list_closed_wips(self, since: datetime | None) -> list[dict]: ...
    def get_repair_order(self, wip_no: str) -> dict: ...
    def get_job_card(self, wip_no: str) -> dict: ...
    def get_vehicle(self, vin: str) -> dict: ...
    def get_service_history(self, vin: str) -> list[dict]: ...
    def get_coverage_contracts(self, vin: str) -> list[dict]: ...
    def list_attachments(self, wip_no: str) -> list[dict]: ...
    def upload_attachment(self, wip_no: str, kind: str, title: str, caption: str, captured_at: str) -> dict: ...
    def record_fact(self, wip_no: str, field: str, value: str) -> dict: ...
    def get_labour_ops(self, programme: str, query: str | None, codes: list[str] | None) -> list[dict]: ...
    def get_condition_codes(self, programme: str, system: str | None) -> list[dict]: ...
    def get_parts(self, wip_no: str) -> list[dict]: ...
    def write_claim_status(self, wip_no: str, claim_ref: str, status: str, amount: float | None) -> None: ...
    def post_credit_note(self, claim_ref: str, amount: float, ref: str, paid_at: str) -> None: ...


@runtime_checkable
class OemConnector(Protocol):
    programme: str
    def capabilities(self) -> dict: ...
    def credential_spec(self) -> dict: ...
    def find_campaigns(self, vin: str) -> list[dict]: ...
    def build_payload(self, claim: dict) -> dict: ...
    def validate_payload(self, payload: dict) -> list[dict]: ...
    def request_pre_authorisation(self, req: dict) -> dict: ...
    def get_pre_authorisation(self, ticket: str) -> dict: ...
    def decide_pre_authorisation(self, ticket: str, approved: bool, actor: str) -> dict: ...
    def submit_claim(self, payload: dict, idem_key: str) -> dict: ...
    def get_claim_status(self, oem_claim_id: str) -> dict: ...
    def resubmit_claim(self, oem_claim_id: str, payload: dict, idem_key: str) -> dict: ...
    def list_credit_notes(self, since: str | None) -> list[dict]: ...
    def map_rejection(self, raw: dict) -> list[str]: ...


@runtime_checkable
class LLMProvider(Protocol):
    name: str
    def chat(self, request: dict) -> dict: ...
    def info(self) -> dict: ...


class JobQueue(Protocol):
    def enqueue(self, kind: str, claim_id: str | None, payload: dict, idem_key: str, priority: int = 100,
                delay_s: float = 0) -> int | None: ...
    def lease(self, n: int, ttl_s: int) -> list[dict]: ...
    def ack(self, job_id: int) -> None: ...
    def nack(self, job_id: int, error: str, retry_in_s: float) -> None: ...


class EventBus(Protocol):
    def publish(self, topic: str, event: dict, conn: Any = None) -> None: ...
    def subscribe(self, after_id: int = 0) -> Iterator[dict]: ...


class BlobStore(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> str: ...
    def get(self, key: str) -> bytes: ...
    def url(self, key: str) -> str: ...


class SecretStore(Protocol):
    def get(self, ref: str) -> str: ...
